/*
===============================================================================
Script: 01_create_pipeline_audit.sql
Purpose: Create persistent pipeline execution-event auditing.

Description:
    Stores append-only audit events generated by
    Apache Airflow pipeline executions.

    Events include:
      STARTED     - Pipeline execution started.
      SUCCESS     - Pipeline execution completed.
      FAILED      - Pipeline execution failed.
      TASK_FAILED - An individual pipeline task failed.

    Timestamps are stored in UTC.

Execution:
    Run once during setup.
    Safe to rerun without deleting existing records.
===============================================================================
*/

USE DataWarehouse;
GO

-- Create a dedicated schema for monitoring data.
IF SCHEMA_ID(N'audit') IS NULL
BEGIN
    EXEC(N'CREATE SCHEMA audit');
END;
GO

-- Create the execution-event table.
IF OBJECT_ID(
    N'audit.pipeline_run_events',
    N'U'
) IS NULL
BEGIN

    CREATE TABLE audit.pipeline_run_events (

        event_id BIGINT IDENTITY(1,1) NOT NULL,

        dag_id NVARCHAR(250) NOT NULL,

        run_id NVARCHAR(250) NOT NULL,

        event_type VARCHAR(20) NOT NULL,

        task_id NVARCHAR(250) NULL,

        event_time_utc DATETIME2(3) NOT NULL
            CONSTRAINT DF_pipeline_events_time
            DEFAULT SYSUTCDATETIME(),

        details NVARCHAR(2000) NULL,

        CONSTRAINT PK_pipeline_run_events
            PRIMARY KEY (event_id),

        CONSTRAINT CK_pipeline_event_type
            CHECK (
                event_type IN (
                    'STARTED',
                    'SUCCESS',
                    'FAILED',
                    'TASK_FAILED'
                )
            )
    );

    -- Improve lookup performance by DAG and run.
    CREATE INDEX IX_pipeline_events_run
    ON audit.pipeline_run_events (
        dag_id,
        run_id,
        event_time_utc DESC
    );

END;
GO
